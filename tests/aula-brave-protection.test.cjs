const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const dir=path.resolve(__dirname,'..');
const js=fs.readFileSync(path.join(dir,'js/aula-control.js'),'utf8');
const html=fs.readFileSync(path.join(dir,'app.html'),'utf8');
const win=fs.readFileSync(path.join(dir,'windows/Bloquear-Brave-Krueka.ps1'),'utf8');
const readme=fs.readFileSync(path.join(dir,'windows/README.md'),'utf8');
new vm.Script(js);
assert.match(html,/js\/aula-control\.js\?v=20261031a/);
assert.match(js,/Brave: sin verificación del bloqueo real/);
assert.doesNotMatch(js,/Protección Brave:[^<]+Instalada/);
assert.match(js,/comprobador y reparador local de Brave/);
assert.match(win,/\[ValidateSet\("Comprobar","Aplicar"\)\]/);
assert.match(win,/BraveSoftware\\Brave\\URLBlocklist/);
assert.match(win,/New-NetFirewallRule/);
assert.match(win,/-Direction Outbound -Action Block/);
assert.match(win,/-Program \$exe/);
assert.match(win,/Test-Path -LiteralPath \$p/);
assert.match(win,/Get-CimInstance Win32_Process/);
assert.match(win,/WindowsPrincipal/);
assert.match(win,/Get-NetFirewallProfile/);
assert.match(win,/reg\.exe export/);
assert.doesNotMatch(win,/Stop-Process|Remove-Item -Path|Uninstall/i);
assert.match(readme,/NO certifica|NO esta confirmada|NO está confirmada|NO es posible/);
assert.match(readme,/no se instala de forma remota/i);
const box={innerHTML:''};
const ctx={$:id=>id==='aula-cuerpo'?box:null,db:{},Date,console,esc:s=>String(s??'')};
vm.createContext(ctx);vm.runInContext(js,ctx);
vm.runInContext('AulaControl.cache={devices:[{id:"test-device",label:"PC de prueba",enabled:true,kiosk_enabled:true,desktop_mode:"office",desktop_mode_observed:"office",kiosk_error:"",agent_version:"0.5",last_seen:new Date().toISOString(),allowed:["krueka.com"]}],requests:[]};AulaControl.render();',ctx);
assert.match(box.innerHTML,/Brave: sin verificación del bloqueo real/);
assert.doesNotMatch(box.innerHTML,/Protección Brave: Instalada/);
assert.match(box.innerHTML,/comprobador y reparador local de Brave/);
console.log('PASS: no se presume protegido Brave por la version del agente; guia de verificacion local.');
