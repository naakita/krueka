const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const base=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(base,p),'utf8');
const ps=read('windows/Blindar-Sesiones-Krueka.ps1');
const ui=read('js/aula-control.js');
const html=read('app.html');
const docs=read('windows/README.md');
const cmd=read('windows/APLICAR-SEGURIDAD-SESIONES-COMO-ADMIN.cmd');
const check=read('windows/COMPROBAR-SESIONES-KRUEKA.cmd');
new vm.Script(ui);
assert.match(html,/js\/aula-control\.js\?v=20261026a/);
assert.match(ui,/Seguridad al cambiar de cuenta: sin comprobar en Windows/);
assert.match(ps,/\[ValidateSet\("Comprobar","Aplicar"\)\]/);
assert.match(ps,/HideFastUserSwitching/);
assert.match(ps,/HKLM:\\SOFTWARE\\Policies\\Microsoft\\Edge/);
assert.match(ps,/HKLM:\\SOFTWARE\\Policies\\Google\\Chrome/);
assert.match(ps,/URLBlocklist/);
assert.match(ps,/URLAllowlist/);
assert.match(ps,/https:\/\/www\.krueka\.com\/\*/);
assert.match(ps,/Get-LocalGroupMember/);
assert.match(ps,/Get-LocalUser/);
assert.match(ps,/Get-NetFirewallProfile/);
assert.match(ps,/New-NetFirewallRule/);
assert.match(ps,/Bloquear-Brave-Krueka\.ps1/);
assert.match(ps,/Respaldo "HKLM\\SOFTWARE\\Policies\\Microsoft\\Edge"/);
assert.match(ps,/respaldo|Respaldo/);
assert.doesNotMatch(ps,/Disable-LocalUser|Remove-LocalUser|Set-LocalUser|Set-LocalUserPassword|Set-NetFirewallProfile|net user .*\/active:no/i);
assert.match(docs,/NO impide iniciar otra sesión|NO impide iniciar otra sesi[oó]n|NO impide iniciar otra sesi/);
assert.match(docs,/solo tras validar/);
assert.match(cmd,/-Modo Aplicar/);
assert.match(check,/-Modo Comprobar/);
const box={innerHTML:''};
const ctx={$:id=>id==='aula-cuerpo'?box:null,db:{},Date,console,esc:s=>String(s||'')};
vm.createContext(ctx);
vm.runInContext(ui,ctx);
vm.runInContext('AulaControl.cache={devices:[],requests:[]};AulaControl.render();',ctx);
assert.match(box.innerHTML,/Seguridad al cambiar de cuenta: sin comprobar en Windows/);
