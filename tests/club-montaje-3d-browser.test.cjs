const fs=require('node:fs'),path=require('node:path'),os=require('node:os'),assert=require('node:assert/strict'),vm=require('node:vm');
const {chromium}=require('playwright');
const root=path.resolve(__dirname,'..');
const fixture=fs.readFileSync(path.join(__dirname,'studio-classroom-browser.test.cjs'),'utf8');
const setup=vm.runInNewContext(fixture.match(/const setup=(`[^]*?`);\nconst smoke=/)[1]);
(async()=>{
 const temp=fs.mkdtempSync(path.join(os.tmpdir(),'kr-montaje-')),f=path.join(temp,'club.html');
 fs.writeFileSync(f,fs.readFileSync(path.join(root,'club-krueka.html'),'utf8').replace('<head>','<head><base href="file://'+root+'/">'+setup));
 const browser=await chromium.launch({executablePath:process.env.STUDIO_CHROMIUM||'/usr/bin/chromium',headless:true,args:['--no-sandbox','--no-zygote','--disable-dev-shm-usage']});
 try{
  const page=await browser.newPage({viewport:{width:1280,height:850}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.route(/^https?:/,route=>route.abort());
  await page.goto('file://'+f);
  await page.waitForFunction(()=>window.KruekaStudioAccess?.ready);
  await page.evaluate(()=>KruekaStudioAccess.login('TEST01'));
  await page.getByRole('button',{name:/Nuevo proyecto/}).click();
  const before=await page.evaluate(()=>StudioIA.projectId);
  await page.locator('#kc-new-world').click();
  await page.locator('#k3d-builder').waitFor();
  const start=await page.evaluate(()=>({id:StudioIA.projectId,files:{...StudioIA.files}}));
  assert.notEqual(start.id,before);
  assert.equal(await page.frameLocator('#ks-frame').locator('#game-title').textContent(),'Mi mundo 3D');
  const pick=async(category,label)=>{await page.locator('#k3d-category').selectOption(category);await page.locator('#k3d-piece').selectOption({label});};
  await pick('ambiente','Montañas nevadas');
  await page.locator('#k3d-apply-part').click();
  await page.getByText(/Montañas nevadas aplicado/).waitFor();
  await pick('personaje','Piloto celeste');
  await page.locator('#k3d-apply-part').click();
  await pick('movimiento','Correr y saltar');
  await page.locator('#k3d-apply-part').click();
  await pick('vehiculo','Avión de exhibición');
  await page.locator('#k3d-copy-code').click();
  const editor=page.locator('#k3d-paste-code');
  const template=JSON.parse(await editor.inputValue());template.name='Mi avión verde';template.objects[0].color='#348a67';
  await editor.fill('{"version":1,\n"category":}');
  await page.locator('#k3d-apply-paste').click();
  await page.getByText(/Sintaxis.*línea 2/).waitFor();
  const blocked={...template,objects:[{...template.objects[0],x:0,z:11}]};
  await editor.fill(JSON.stringify(blocked));
  await page.locator('#k3d-apply-paste').click();
  await page.getByText(/Coherencia.*punto de salida/).waitFor();
  assert.ok(await page.evaluate(()=>!StudioKits.read(StudioIA.files).objects.some(o=>o.type==='airplane')));
  await editor.fill(JSON.stringify(template,null,2));
  await page.locator('#k3d-save-part').click();
  await page.getByText(/Parte guardada en la biblioteca/).waitFor();
  await page.locator('#k3d-apply-paste').click();
  await page.getByText(/Mi avión verde aplicado/).waitFor();
  const live=await page.evaluate(()=>({cfg:StudioKits.read(StudioIA.files),files:{...StudioIA.files}}));
  assert.equal(live.cfg.avatarStyle,'piloto');
  assert.equal(live.cfg.speed,7);
  assert.equal(live.cfg.objects.find(o=>o.type==='airplane').color,'#348a67');
  assert.equal(live.cfg.objects.filter(o=>o.type==='mountain').length,2);
  assert.equal(live.files['game.js'],start.files['game.js']);
  assert.equal(live.files['index.html'],start.files['index.html']);
  if(process.env.STUDIO_SCREENSHOT_DIR)await page.screenshot({path:path.join(process.env.STUDIO_SCREENSHOT_DIR,'montaje-3d.png')});
  await page.locator('#k3d-edit').click();
  assert.ok(await page.locator('[data-object-field=color]').isVisible());
  await page.locator('#k3d-play').click();
  await page.frameLocator('#ks-frame').getByRole('button',{name:'Editar escena',exact:false}).waitFor();
  await page.locator('#k3d-save').click();
  await page.getByText(/Proyecto y piezas guardados/).waitFor();
  await page.evaluate(async()=>{await StudioIA.close();await KruekaStudioAccess.login('TEST01');});
  await page.locator('#ks-projects').click();
  await page.locator('[data-project="'+start.id+'"]').click();
  await page.locator('#k3d-builder').waitFor();
  const reopened=await page.evaluate(()=>({id:StudioIA.projectId,part:JSON.parse(StudioIA.files['mis-plantillas-3d.json'])[0]}));
  assert.equal(reopened.id,start.id);
  assert.equal(reopened.part.name,'Mi avión verde');
  await page.setViewportSize({width:390,height:820});
  assert.ok(await page.locator('#k3d-category').isVisible());
  assert.ok(await page.evaluate(()=>document.getElementById('krueka-studio').scrollWidth<=innerWidth+1));
  await page.evaluate(async()=>{await StudioIA.close();await KruekaStudioAccess.login('TEST02');});
  await page.locator('#ks-projects').click();
  await page.getByRole('dialog',{name:'Mis proyectos'}).waitFor();
  assert.equal(await page.locator('[data-project="'+start.id+'"]').count(),0);
  assert.deepEqual(errors,[]);
  console.log('PASS: nuevo mundo, plantillas aditivas, sintaxis, ruta, color editable, piezas privadas, prueba, guardado y reapertura; escritorio y móvil.');
 }finally{await browser.close();fs.rmSync(temp,{recursive:true,force:true});}
})().catch(e=>{console.error(e);process.exitCode=1});
