const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const ctx={};ctx.window=ctx;vm.createContext(ctx);
for(const n of ['club-studio-kits.js','club-studio-3d.js','club-studio-3d-toolbox.js'])vm.runInContext(fs.readFileSync(path.join(root,'js',n),'utf8'),ctx);
const K=ctx.StudioKits,engine=ctx.Studio3D,tools=ctx.Krueka3DToolbox;
const choices={cubes:'Aldea de cubos',mine:'Mina de bloques',ice:'Valle de hielo',slalom:'Parque de obstáculos',neon:'Laboratorio neón',fortress:'Fortaleza de bloques'};
const start=K.read(tools.initialWorld());
const inline=JSON.stringify(start);
for(const [id,title] of Object.entries(choices))test(title+' se puede agregar como una zona jugable o usar como piezas',()=>{
 const spec=tools.template(id);
 assert.ok(spec.objects.length>=16&&spec.objects.length<=30);
 assert.ok(spec.objects.some(o=>o.type==='crystal'),'contiene una meta para el recorrido');
 assert.equal(JSON.stringify(spec),JSON.stringify(tools.template(id)),'posiciones estables');
 const single=engine.normalise(spec);
 assert.equal(tools.validate(single).ok,true,'se llega a los cristales y al portal desde la entrada');
 const world=tools.appendZone(start,id);
 assert.equal(world.zones[0].name,title);
 assert.equal(world.zones[0].theme,spec.theme);
 assert.equal(world.objects[0].id,'cristal-prueba','preserva el trabajo existente');
 const pieces=world.objects.filter(o=>o.zone===1);
 assert.equal(pieces.length,spec.objects.length);
 assert.equal(new Set(world.objects.map(o=>o.id)).size,world.objects.length);
 assert.equal(tools.validate(world).ok,true,'ruta continua y recompensas alcanzables desde otra zona');
 assert.equal(JSON.stringify(start),inline,'no altera la configuración original');
 const available=tools.library().find(p=>p.name===title);
 assert.equal(available.category,'ambiente');
 assert.ok(available.objects.every(o=>o.type!=='crystal'),'decorar la zona actual no cambia sus objetivos');
 const part=tools.parsePiece(JSON.stringify(available));
 const decorated=tools.mergePiece(start,part);
 assert.equal(decorated.objects.length,1+part.objects.length);
 assert.ok(tools.validate(decorated).ok,'la plantilla conserva la ruta del mundo inicial');
});
test('los ambientes usan recursos propios y no se limitan a cambiar colores',()=>{
 const blueprints=Object.keys(choices).map(id=>tools.template(id));
 const formations=blueprints.map(o=>o.objects.map(p=>[p.type,p.x,p.z]).join('|'));
 assert.equal(new Set(formations).size,blueprints.length);
 assert.ok(tools.template('neon').objects.some(o=>o.type==='drone'),'drones reales del motor');
 assert.ok(tools.template('slalom').objects.some(o=>o.type==='crate'&&o.height<=.9),'obstáculos bajos para esquivar o saltar');
 assert.doesNotMatch(JSON.stringify(blueprints),/https?:\/\/|(?:minecraft|roblox)/i);
});
