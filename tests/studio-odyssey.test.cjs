const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
const env={console,JSON,Object,Array,Math,Number,String,Date,Map,Set};env.window=env;vm.createContext(env);
for(const file of ['js/club-studio-kits.js','js/club-studio-3d.js','js/club-studio-forge.js','js/club-studio-odyssey.js'])vm.runInContext(read(file),env);
