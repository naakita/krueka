assert.ok(entry.indexOf("'club-studio-odyssey.js'")>entry.indexOf("'club-studio-ai.js'"));
assert.ok(creative.includes("first:'odyssey3d'"));
const demo=read('ejemplos/krueka-odyssey.html');
assert.ok(demo.includes("create('odyssey3d')")&&demo.includes('sandbox="allow-scripts"'));
assert.ok(demo.includes("connect-src \\'none\\'"));
console.log('PASS: Odyssey 3D 5-file project, world, missions, graphics fallback, options, catalog, public sandbox and no external services.');
