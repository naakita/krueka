const f=K.create('odyssey3d'),cfg=K.read(f);
assert.equal(cfg.kind,'odyssey3d');assert.equal(cfg.objects.filter(x=>x.type==='crystal').length,3);
assert.equal(cfg.objects.filter(x=>x.type==='drone').length,2);
assert.equal(cfg.lives,5);assert.equal(cfg.environment.weather,'clear');
for(const name of ['index.html','style.css','game-config.js','game.js','LEEME.md'])assert.ok(f[name]&&f[name].length>120);
for(const [name,content] of Object.entries(f))assert.ok(content.length<=120000,name);
assert.ok(Object.values(f).reduce((sum,v)=>sum+v.length,0)<65000);
assert.ok(f['index.html'].includes('id="odyssey-map"'));assert.ok(f['index.html'].includes('id="odyssey-drive"'));assert.ok(f['index.html'].includes('id="odyssey-bar"'));
assert.match(f['game.js'],/function odysseyDrive\(/);assert.match(f['game.js'],/function odysseyUseTerminal\(/);assert.match(f['game.js'],/terminals.size===2/);
assert.match(f['game.js'],/function odysseyScene\(/);
assert.match(f['game.js'],/getContext\('webgl'/);assert.match(f['game.js'],/getContext\('2d'\)/);
new vm.Script(f['game.js']);new vm.Script(f['game-config.js']);
assert.ok(!/https?:\/\/|import\s*\(|\bfetch\(/i.test(Object.values(f).join('')),'Proyecto independiente de servicios externos');
const configured=O.clean({...cfg,odyssey:{carColor:'javascript:alert(1)',neon:false},environment:{district:'impossible',weather:'rain',light:'cryo'},speed:500});
assert.equal(configured.odyssey.carColor,'#24c7d9');
assert.equal(configured.environment.district,'city');assert.equal(configured.environment.weather,'rain');
assert.equal(configured.speed,9);assert.equal(configured.odyssey.neon,false);
assert.throws(()=>O.enhance('not a game'),/incompatible/);
const app=read('app.html'),entry=read('js/club-studio-access.js'),creative=read('js/club-studio-creative.js');
assert.ok(app.includes('js/club-studio-odyssey.js?v=20261023d'));
