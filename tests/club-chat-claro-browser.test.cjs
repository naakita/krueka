const fs=require('node:fs'),path=require('node:path'),os=require('node:os'),assert=require('node:assert/strict'),vm=require('node:vm');
const {chromium}=require('playwright');
const root=path.resolve(__dirname,'..');
const fixture=fs.readFileSync(path.join(__dirname,'studio-classroom-browser.test.cjs'),'utf8');
const setup=vm.runInNewContext(fixture.match(/const setup=(`[^]*?`);\nconst smoke=/)[1]);
(async()=>{
 const temp=fs.mkdtempSync(path.join(os.tmpdir(),'kr-chat-claro-')),f=path.join(temp,'club.html');
 fs.writeFileSync(f,fs.readFileSync(path.join(root,'club-krueka.html'),'utf8').replace('<head>','<head><base href="file://'+root+'/">'+setup));
 const browser=await chromium.launch({executablePath:process.env.STUDIO_CHROMIUM||'/usr/bin/chromium',headless:true,args:['--no-sandbox','--no-zygote','--disable-dev-shm-usage']});
 try{
  const page=await browser.newPage({viewport:{width:1365,height:670}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.route(/^https?:/,route=>route.abort());
  await page.goto('file://'+f);
  await page.waitForFunction(()=>window.KruekaStudioAccess?.ready);
  await page.evaluate(()=>KruekaStudioAccess.login('TEST01'));
  await page.locator('[data-creative-path=juegos]').click();
  await page.locator('[data-creative-kit=pabellon-juego]').click();
  await page.waitForFunction(()=>!StudioIA.busy&&StudioKits.read(StudioIA.files)?.kind==='pabellon-juego');
  await page.locator('[data-tab=ai]').first().click();
  await page.locator('#ks-simple-head').getByRole('heading',{name:'¿Qué querés cambiar?'}).waitFor();
  const inp=page.getByLabel('Escribí tu pedido');
  assert.ok(await inp.isVisible());
  assert.equal(await page.locator('#ks-send').textContent(),'Aplicar ayuda local');
  assert.equal(await page.locator('#ks-ai .ks-modes').isVisible(),false);
  assert.equal(await page.locator('#ks-project-context').isVisible(),false);
  await page.frameLocator('#ks-frame').getByText('El pabellón de las semillas',{exact:true}).waitFor();
  const input=await inp.boundingBox();
  const history=await page.locator('#ks-simple-history').boundingBox();
  assert.ok(input.y<input.y+input.height&&input.y+input.height<history.y);
  if(process.env.STUDIO_SCREENSHOT_DIR)await page.screenshot({path:path.join(process.env.STUDIO_SCREENSHOT_DIR,'chat-claro-pabellon.png')});
  await page.getByRole('button',{name:'Usar un ejemplo'}).click();
  assert.equal(await inp.inputValue(),'Cambiá la luz del jardín a noche.');
  await inp.fill('Me gustaría iluminar el jardín');
  await page.getByRole('button',{name:'Usar un ejemplo'}).click();
  assert.equal(await inp.inputValue(),'Me gustaría iluminar el jardín');
  const before=await page.evaluate(()=>({...StudioIA.files}));
  await page.locator('#ks-send').click();
  await page.getByText(/No cambié el juego/).waitFor();
  assert.equal(await page.evaluate(()=>StudioKits.read(StudioIA.files).light),'tarde');
  await inp.fill('Cambiá la luz del jardín a noche.');
  await page.locator('#ks-send').click();
  await page.getByText(/Luz inicial: Atardecer → Noche/).waitFor();
  await page.waitForFunction(()=>!StudioIA.busy);
  await page.waitForFunction(()=>StudioKits.read(StudioIA.files).light==='noche');
  assert.equal(await page.frameLocator('#ks-frame').locator('#luz').inputValue(),'noche');
  assert.deepEqual(await page.evaluate(before=>Object.keys(StudioIA.files).filter(k=>StudioIA.files[k]!==before[k]),before),['game-config.js']);
  await inp.fill('Cambiá la meta a 2 semillas.');
  await page.locator('#ks-send').click();
  await page.getByText(/Semillas para ganar: 3 → 2/).waitFor();
  await page.waitForFunction(()=>!StudioIA.busy);
  await page.frameLocator('#ks-frame').getByText('0 de 2 semillas',{exact:true}).waitFor();
  assert.equal(await page.frameLocator('#ks-frame').locator('#luz').inputValue(),'noche');
  await page.evaluate(()=>StudioIA.restore());
  await page.frameLocator('#ks-frame').getByText('0 de 3 semillas',{exact:true}).waitFor();
  const more=page.getByRole('button',{name:'Más opciones'});
  await more.click();
  assert.equal(await page.locator('#ks-ai .ks-modes').isVisible(),true);
  await page.getByRole('button',{name:'Ocultar opciones'}).click();
  await page.getByRole('button',{name:'Abrir las reglas'}).click();
  await page.waitForFunction(()=>StudioIA.tab==='create');
  await page.locator('[data-tab=ai]').first().click();
  await page.setViewportSize({width:390,height:820});
  assert.ok(await inp.isVisible());
  assert.ok(await page.locator('#ks-send').isVisible());
  assert.ok(await page.evaluate(()=>document.getElementById('krueka-studio').scrollWidth<=innerWidth+1));
  if(process.env.STUDIO_SCREENSHOT_DIR)await page.screenshot({path:path.join(process.env.STUDIO_SCREENSHOT_DIR,'chat-claro-movil.png')});
  await page.evaluate(()=>{StudioIA.updateAI({ready:true,configured:true,provider:'Cloudflare'});StudioIA.renderAIStatus();StudioIA.lock(false);});
  assert.equal(await page.locator('#ks-send').textContent(),'Enviar a la IA');
  await page.evaluate(async()=>{await StudioIA.close();await KruekaStudioAccess.login('TEST02');StudioIA.showTab('ai');});
  assert.doesNotMatch(await page.locator('#ks-chat').innerText(),/Me gustaría iluminar/);
  assert.deepEqual(errors,[]);
  console.log('PASS: el Pabellón abre con chat primero, vista previa, luz y meta locales, archivos intactos, deshacer, reglas y opciones; móvil e historial aislado.');
 }finally{await browser.close();fs.rmSync(temp,{recursive:true,force:true});}
})().catch(e=>{console.error(e);process.exitCode=1});
